'use strict';
const assert = require('node:assert/strict');
const {amount,createWallet,debit,credit,payoutForBets} = require('./compact-wallet');
const a='1234567890123456',b='9876543210123456';
let w=createWallet('1000000');
let tx=debit(w,a,'500000');assert.equal(tx.wallet.balance,'500000');w=tx.wallet;
assert.equal(debit(w,a,'500000').repeated,true);
assert.throws(()=>debit(w,a,'400000'),/OPERATION_ID_AMOUNT_CONFLICT/);
assert.throws(()=>credit(w,a,'500000'),/OPERATION_ID_REUSED/);
assert.throws(()=>debit(w,b,'600000'),/INSUFFICIENT_COINS/);
tx=credit(w,b,'9999999999000000000000');w=tx.wallet;
assert.equal(w.balance,'9999999999000000500000');
assert.equal(credit(w,b,'9999999999000000000000').repeated,true);
assert.throws(()=>credit(w,b,'1'),/OPERATION_ID_AMOUNT_CONFLICT/);
assert.equal(payoutForBets([{foodIndex:0,amount:'1000000'},{foodIndex:0,amount:'1000000'}],0,'45'),'90000000');
assert.equal(amount('9999999999000000000000'),9999999999000000000000n);
assert.throws(()=>amount(9999999999000000000000),/UNSAFE_AMOUNT/);
console.log('Wallet V2 arithmetic/idempotency tests: PASS');
